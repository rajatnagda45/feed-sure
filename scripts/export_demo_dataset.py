"""Export attributed mapped venues and synthetic demo records for Supabase."""

from __future__ import annotations

import argparse
import csv
import json
import random
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from demo_scenarios import demo_readiness_rows
from seed_data import DEFAULT_DEMO_LOCATIONS, load_demo_locations

ROOT = Path(__file__).resolve().parents[1]
TABLE_KEYS = {
    "feedsure_demo_generators": "generator_id",
    "feedsure_demo_readiness": "generator_id,collection_date",
    "feedsure_demo_history": "generator_id,date",
}


def build_dataset(
    collection_date: date, locations_path: Path = DEFAULT_DEMO_LOCATIONS
) -> dict[str, Any]:
    """Keep source geography exact and mark all operational values as simulated."""
    locations = load_demo_locations(locations_path)
    rng = random.Random(20261011)
    history = []
    for location in locations:
        for offset in range(14, 0, -1):
            history.append(
                {
                    "generatorId": location["generatorId"],
                    "date": (collection_date - timedelta(days=offset)).isoformat(),
                    "kg": rng.randint(120, 220),
                    "simulated": True,
                    "quantitySource": "SIMULATED",
                }
            )
    return {
        "schemaVersion": 3,
        "datasetId": "harohalli-osm-demo-v1",
        "collectionDate": collection_date.isoformat(),
        "geography": {
            key: locations[0]["locationSource"][key]
            for key in (
                "provider",
                "attribution",
                "license",
                "licenseUrl",
                "copyrightUrl",
                "retrievedOn",
            )
        },
        "note": "OSM venue references; no enrolled suppliers or measured waste quantities. "
        "Readiness and history are simulated. No credentials are included.",
        "generators": [
            {
                **location,
                "venueName": location["name"],
                "name": f"{location['name']} (demo)",
                "pickupStart": "06:00",
                "pickupEnd": "09:00",
                "defaultLang": "en",
                "simulated": True,
                "verification": {
                    "participationVerified": False,
                    "wasteStreamVerified": False,
                    "pickupEntranceVerified": False,
                    "venueOperationVerified": False,
                },
            }
            for location in locations
        ],
        "readiness": [
            {**row, "simulated": True, "quantitySource": "SIMULATED"}
            for row in demo_readiness_rows(collection_date)
        ],
        "history": history,
    }


def table_rows(dataset: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    """Normalize the portable contract into three explicitly named demo tables."""
    return {
        "feedsure_demo_generators": [
            {
                "generator_id": row["generatorId"],
                "name": row["name"],
                "venue_name": row["venueName"],
                "type": row["type"],
                "address": row["address"],
                "lat": row["lat"],
                "lng": row["lng"],
                "location_source": row["locationSource"],
                "verification": row["verification"],
                "simulated": True,
            }
            for row in dataset["generators"]
        ],
        "feedsure_demo_readiness": [
            {
                "generator_id": row["generatorId"],
                "collection_date": row["collectionDate"],
                "status": row["status"],
                "confirmed_kg": row["confirmedKg"],
                "weight_source": row["weightSource"],
                "window_start": row["window"]["start"] if row["window"] else None,
                "window_end": row["window"]["end"] if row["window"] else None,
                "reason": row["reason"],
                "simulated": True,
                "quantity_source": "SIMULATED",
            }
            for row in dataset["readiness"]
        ],
        "feedsure_demo_history": [
            {
                "generator_id": row["generatorId"],
                "date": row["date"],
                "kg": row["kg"],
                "simulated": True,
                "quantity_source": "SIMULATED",
            }
            for row in dataset["history"]
        ],
    }


def seed_sql(tables: dict[str, list[dict[str, Any]]]) -> str:
    """Render transactionally replayable insertions that preserve existing edits."""
    statements = [
        "-- Generated by scripts/export_demo_dataset.py; no credentials.",
        "-- Real OSM geography, simulated operational data. Apply migration first.",
        "begin;",
    ]
    for table, rows in tables.items():
        payload = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
        # Derive a delimiter absent from data, including untrusted mapped venue names.
        delimiter = "$feedsure$"
        while delimiter in payload:
            delimiter = delimiter[:-1] + "x$"
        statements.append(
            f"insert into public.{table}\n"
            f"select * from jsonb_populate_recordset(null::public.{table},\n"
            f"{delimiter}{payload}{delimiter}::jsonb)\n"
            f"on conflict ({TABLE_KEYS[table]}) do nothing;"
        )
    return "\n\n".join(statements + ["commit;", ""])


def write_exports(dataset: dict[str, Any], output: Path, sql_path: Path) -> None:
    """Write JSON, CSV, REST payloads and SQL from the same validated dataset."""
    output.mkdir(parents=True, exist_ok=True)
    tables = table_rows(dataset)
    (output / "feedsure_demo.json").write_text(
        json.dumps(dataset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    for table, rows in tables.items():
        (output / f"{table}.json").write_text(
            json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        with (output / f"{table}.csv").open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            for row in rows:
                writer.writerow(
                    {
                        key: json.dumps(value, ensure_ascii=False)
                        if isinstance(value, (dict, bool))
                        else value
                        for key, value in row.items()
                    }
                )
    sql_path.parent.mkdir(parents=True, exist_ok=True)
    sql_path.write_text(seed_sql(tables), encoding="utf-8")


def main() -> None:
    """Build a portable seed without connecting to AWS or Supabase."""
    tomorrow = datetime.now(timezone(timedelta(hours=5, minutes=30))).date() + timedelta(days=1)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--date", type=date.fromisoformat, default=tomorrow)
    parser.add_argument("--locations", type=Path, default=DEFAULT_DEMO_LOCATIONS)
    parser.add_argument("--output", type=Path, default=ROOT / "data/exports")
    parser.add_argument("--sql-output", type=Path, default=ROOT / "supabase/seed.sql")
    args = parser.parse_args()
    dataset = build_dataset(args.date, args.locations)
    write_exports(dataset, args.output, args.sql_output)
    print(
        f"Exported 10 mapped venues, 10 simulated readiness states and 140 simulated history "
        f"rows for {args.date}. No remote data was written."
    )


if __name__ == "__main__":
    main()
